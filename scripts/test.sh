#!/bin/sh
# The unit tests, built once and run from one binary:
#
#   scripts/test.sh [-k] [TEST...]     # pixi run test-units [test_codec ...]
#   scripts/test.sh --build            # only build it (scripts/build-tests.sh)
#
# Every tests/test_*.mojo but the ones below goes into
# build/tests/multicall-tests, and each test file then runs as its own
# process, build/tests/<test>, a link to it. The library code the tests share
# is compiled once, not once per test file (census's scripts/test.sh, which
# this follows). With TEST arguments (file names, with or without tests/ and
# .mojo) only those run; the binary still has them all. -k keeps going after
# a failure.
#
# Not in it, each built on its own:
# - tests/test_head_loop.mojo (`pixi run test-head-loop`): its main ignores
#   SIGPIPE with `signal(13, SIG_IGN)`, an integer for the handler, where
#   dista's own code declares `signal` with a function (dista.signals). Mojo
#   allows one signature per C symbol in a program, so the two can't be in
#   one binary.
# - tests/test_libc_abi.mojo (`pixi run test-libc-abi`): it declares libc's
#   socket calls as Mosaad-M/tcp does, in one program with dista's own, and
#   must fail to build if the two disagree. In a binary with every test, a
#   clash would break all of them, or be hidden by another file's declaration.
# - tests/test_parquet_tasks.mojo and tests/test_iceberg_scan.mojo: they need
#   the data environment (`pixi run -e data test-parquet`, `test-iceberg`).
#
# The tests are registered by name here, each `def test_...` at column 0,
# not found with `__functions_in_module()`: in a module that is imported,
# rather than compiled as the main file, that list comes back incomplete
# (Mojo 1.2.0), and a test file would pass having run nothing. The count the
# binary reports is checked against the functions found here. A test file's
# `main` is therefore not called: it may only run the tests, and what a file
# needs done around them goes in `def before_tests() raises` and
# `def after_tests() raises`, called here and by its main (as in census's
# tests/test_fetch.mojo).
#
# One file alone, without this: scripts/mojo-build.sh -I src $DEP_INC
# tests/test_codec.mojo -o build/test-codec && ./build/test-codec
# Run inside `pixi run`.
set -eu
keep=""
build_only=""
[ "${1:-}" = -k ] && { keep=1; shift; }
[ "${1:-}" = --build ] && { build_only=1; shift; }
dir=build/tests
gen=build/multicall-gen/tests
mkdir -p "$gen" "$dir"
main=$gen/multicall_tests_main.mojo
tests=""
for f in tests/test_*.mojo; do
    case "$f" in
    tests/test_head_loop.mojo | tests/test_libc_abi.mojo | tests/test_parquet_tasks.mojo | tests/test_iceberg_scan.mojo) ;;
    *) tests="$tests $f" ;;
    esac
done
functions() { sed -n 's/^def \(test_[A-Za-z0-9_]*\)(.*/\1/p' "$1"; }
{
    echo '"""Generated by scripts/test.sh: the tests of the file basename(argv[0])'
    echo 'names."""'
    echo
    echo 'from std.sys import argv'
    echo 'from std.testing import TestSuite'
    echo
    for f in $tests; do
        m=$(basename "$f" .mojo)
        for t in $(functions "$f"); do echo "from $m import $t as ${m}__$t"; done
        if grep -q '^def before_tests()' "$f"; then
            echo "from $m import before_tests as ${m}__before_tests"
            echo "from $m import after_tests as ${m}__after_tests"
        fi
    done
    echo
    echo
    echo 'def main() raises:'
    echo '    var me = String(argv()[0])'
    echo '    var slash = me.rfind("/")'
    echo '    var name = String(me[byte = slash + 1 :]) if slash >= 0 else me'
    kw=if
    for f in $tests; do
        m=$(basename "$f" .mojo)
        list=""
        for t in $(functions "$f"); do list="$list${m}__$t, "; done
        [ -n "$list" ] || { echo "test.sh: $f has no test" >&2; exit 1; }
        echo "    $kw name == \"$m\":"
        if grep -q '^def before_tests()' "$f"; then
            echo "        ${m}__before_tests()"
            echo '        var failed = False'
            echo '        try:'
            echo "            TestSuite.discover_tests[($list)]().run()"
            echo '        except e:'
            echo '            failed = True'
            echo '            print(e)'
            echo "        ${m}__after_tests()"
            echo '        if failed:'
            echo "            raise Error(\"$m failed\")"
        else
            # Its main is not called, so it may only run the tests.
            [ "$(sed -n '/^def main()/,$p' "$f" | grep -vc '^[[:space:]]*$')" = 2 ] || {
                echo "test.sh: $f: main does more than run the tests; move that to before_tests() and after_tests()" >&2
                exit 1
            }
            echo "        TestSuite.discover_tests[($list)]().run()"
        fi
        kw=elif
    done
    echo '    else:'
    echo '        raise Error(name, ": not a test of this binary")'
} > "$main.tmp"
# Rewritten only when it changed, so scripts/mojo-build.sh's key holds.
if cmp -s "$main.tmp" "$main"; then rm -f "$main.tmp"; else mv -f "$main.tmp" "$main"; fi
t=$(date +%s)
# shellcheck disable=SC2086
scripts/mojo-build.sh -I src -I tests $DEP_INC "$main" -o "$dir/multicall-tests"
echo "test.sh: built in $(($(date +%s) - t)) s"
for f in $tests; do ln -sf multicall-tests "$dir/$(basename "$f" .mojo)"; done
[ -z "$build_only" ] || exit 0

if [ $# -gt 0 ]; then
    tests=""
    for a in "$@"; do
        a=tests/$(basename "$a" .mojo).mojo
        [ -f "$a" ] || { echo "test.sh: no $a" >&2; exit 1; }
        tests="$tests $a"
    done
fi
failed=""
log=$gen/run.log
for f in $tests; do
    m=$(basename "$f" .mojo)
    want=$(functions "$f" | wc -l | tr -d ' ')
    echo "== $f"
    if "$dir/$m" > "$log" 2>&1; then rc=0; else rc=$?; fi
    cat "$log"
    ran=$(sed -n 's/.* \([0-9][0-9]*\) tests run:.*/\1/p' "$log" | tail -1)
    if [ $rc != 0 ]; then
        failed="$failed $m"
    elif [ "${ran:-0}" != "$want" ]; then
        echo "test.sh: $f has $want tests and ran ${ran:-0}" >&2
        failed="$failed $m"
    fi
    [ -z "$failed" ] || [ -n "$keep" ] || break
done
[ -z "$failed" ] || { echo "test.sh: failed:$failed" >&2; exit 1; }
